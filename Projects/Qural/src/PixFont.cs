        /// Ширина строки при масштабе s: символ 5 клеток + 1 клетка промежутка.
        public static int Width(string t, int s) { return t.Length == 0 ? 0 : t.Length * 6 * s - s; }

        public static void Text(Graphics g, string t, int x, int y, int s, Color c)
        {
            using (var br = new SolidBrush(c))
                foreach (char ch0 in t.ToUpperInvariant())
                {
                    string[] gl;
                    if (G.TryGetValue(ch0, out gl))
                        for (int j = 0; j < 7; j++) for (int i = 0; i < 5; i++) if (gl[j][i] == '#') g.FillRectangle(br, x + i * s, y + j * s, s, s);
                    x += 6 * s;
                }
        }

        public static void Right(Graphics g, string t, int xr, int y, int s, Color c) { Text(g, t, xr - Width(t, s), y, s, c); }
        public static void Center(Graphics g, string t, int cx, int y, int s, Color c) { Text(g, t, cx - Width(t, s) / 2, y, s, c); }

        /// Полоска из n квадратиков, закрашено по доле 0…1 (как bar() в pixpng.js).
        public static void Bar(Graphics g, int x, int y, int w, int h, int n, double frac, Color on, Color off)
        {
            int gap = System.Math.Max(2, (int)System.Math.Round(h / 3.0));
            float bw = (w - gap * (n - 1)) / (float)n;
            int filled = (int)System.Math.Round(n * System.Math.Max(0, System.Math.Min(1, frac)));
            using (var a = new SolidBrush(on)) using (var b = new SolidBrush(off))
                for (int i = 0; i < n; i++)
                {
                    int x0 = (int)System.Math.Round(x + i * (bw + gap)), x1 = (int)System.Math.Round(x + i * (bw + gap) + bw);
                    g.FillRectangle(i < filled ? a : b, x0, y, x1 - x0, h);
                }
        }

        /// Полоска из долей разного цвета (например, скорость по подключениям): parts — доли 0…1, по порядку.
        public static void Split(Graphics g, int x, int y, int w, int h, int n, double[] parts, Color[] colors, Color off)
        {
            int gap = System.Math.Max(2, (int)System.Math.Round(h / 3.0));
            float bw = (w - gap * (n - 1)) / (float)n;
            int k = 0; double acc = 0; int[] owner = new int[n];
            for (int i = 0; i < n; i++) owner[i] = -1;
            for (int p = 0; p < parts.Length; p++)
            {
                acc += parts[p];
                int upto = (int)System.Math.Round(n * System.Math.Min(1, acc));
                for (; k < upto; k++) owner[k] = p;
            }
            for (int i = 0; i < n; i++)
                using (var br = new SolidBrush(owner[i] < 0 ? off : colors[owner[i] % colors.Length]))
                {
                    int x0 = (int)System.Math.Round(x + i * (bw + gap)), x1 = (int)System.Math.Round(x + i * (bw + gap) + bw);
                    g.FillRectangle(br, x0, y, x1 - x0, h);
                }
        }
