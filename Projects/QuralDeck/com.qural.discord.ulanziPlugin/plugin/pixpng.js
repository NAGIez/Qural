export class Canvas {
  constructor(w, h, bg = [0, 0, 0, 255]) {
    this.w = w; this.h = h;
    this.px = Buffer.alloc(w * h * 4);
    this.rect(0, 0, w, h, bg);
  }

  rect(x, y, w, h, c) {
    const x0 = Math.max(0, Math.round(x)), y0 = Math.max(0, Math.round(y));
    const x1 = Math.min(this.w, Math.round(x + w)), y1 = Math.min(this.h, Math.round(y + h));
    for (let j = y0; j < y1; j++)
      for (let i = x0; i < x1; i++) {
        const o = (j * this.w + i) * 4;
        this.px[o] = c[0]; this.px[o + 1] = c[1]; this.px[o + 2] = c[2]; this.px[o + 3] = c.length > 3 ? c[3] : 255;
      }
  }

  // ширина строки в пикселях при масштабе s (символ 5 клеток + 1 клетка промежутка)
  static textWidth(text, s) { return text.length ? text.length * 6 * s - s : 0; }

  text(text, x, y, s, c) {
    let cx = Math.round(x);
    for (const ch of String(text).toUpperCase()) {
      const g = FONT[ch] || FONT[' '];
      for (let j = 0; j < 7; j++)
        for (let i = 0; i < 5; i++)
          if (g[j][i] === '#') this.rect(cx + i * s, y + j * s, s, s, c);
      cx += 6 * s;
    }
  }

  textCenter(text, cxm, y, s, c) { this.text(text, cxm - Canvas.textWidth(String(text), s) / 2, y, s, c); }
  textRight(text, xr, y, s, c) { this.text(text, xr - Canvas.textWidth(String(text), s), y, s, c); }

  // полоска из квадратиков: n штук, закрашено по проценту
  bar(x, y, w, h, n, pct, on, off) {
    const gap = Math.max(2, Math.round(h / 3)), bw = (w - gap * (n - 1)) / n;
    const filled = Math.round(n * Math.max(0, Math.min(100, pct)) / 100);
    for (let i = 0; i < n; i++) this.rect(x + i * (bw + gap), y, bw, h, i < filled ? on : off);
  }

  // наложить RGBA-картинку (непрозрачные точки) в позицию x, y
  blit(src, sw, sh, x, y) {
    for (let j = 0; j < sh; j++) {
      const ty = y + j; if (ty < 0 || ty >= this.h) continue;
      for (let i = 0; i < sw; i++) {
        const tx = x + i; if (tx < 0 || tx >= this.w) continue;
        const s = (j * sw + i) * 4;
        if (src[s + 3] < 128) continue;
        const o = (ty * this.w + tx) * 4;
        this.px[o] = src[s]; this.px[o + 1] = src[s + 1]; this.px[o + 2] = src[s + 2]; this.px[o + 3] = 255;
      }
    }
  }

  copy() { const c = Object.create(Canvas.prototype); c.w = this.w; c.h = this.h; c.px = Buffer.from(this.px); return c; }

  png() {
    const raw = Buffer.alloc((this.w * 4 + 1) * this.h);
    for (let j = 0; j < this.h; j++) {
      raw[j * (this.w * 4 + 1)] = 0;
      this.px.copy(raw, j * (this.w * 4 + 1) + 1, j * this.w * 4, (j + 1) * this.w * 4);
    }
    const ihdr = Buffer.alloc(13);
    ihdr.writeUInt32BE(this.w, 0); ihdr.writeUInt32BE(this.h, 4);
    ihdr[8] = 8; ihdr[9] = 6; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
    return Buffer.concat([
      Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
      chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0)),
    ]);
  }
}

const CRC = new Int32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c; });
function crc32(buf) { let c = -1; for (const b of buf) c = CRC[(c ^ b) & 255] ^ (c >>> 8); return (c ^ -1) >>> 0; }
function chunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}
